import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
p.on('pageerror', (e) => console.log('PAGEERROR', String(e).slice(0, 200)));
await p.goto('http://localhost:3000/login');
await p.waitForTimeout(1500);
await p.fill('input[type=email]', 'user-example@gmail.com');
await p.fill('input[type=password]', 'password');
await p.keyboard.press('Enter');
await p.waitForTimeout(9000);
await p.click('button[role=tab]:has-text("Members")');
await p.waitForTimeout(500);
await p.click('button[aria-label="Add a person to this forum"]');
await p.fill('input[role=combobox]', 'Sam');
await p.waitForTimeout(500);
console.log('options:', await p.$$eval('[role=option]', (x) => x.map((y) => y.textContent.replace(/\s+/g, ' ').trim())));
await p.click('[role=option]');
await p.waitForTimeout(3500);
console.log('members now:', await p.$$eval('strong', (x) => x.map((y) => y.textContent.trim()).filter((t) => /member|Samwel|User/.test(t))));
await p.screenshot({ path: '/tmp/shot2.png' });
// full page view
await p.click('button[aria-label="Expand chat"]');
await p.click('[role=menuitem]:has-text("Fit to page")');
await p.waitForTimeout(1200);
await p.click('button[role=tab]:has-text("Members")');
await p.waitForTimeout(600);
console.log('full members tab buttons:', await p.$$eval('button', (bs) => bs.map((x) => x.getAttribute('aria-label') || '').filter((x) => /Add/.test(x))));
await p.screenshot({ path: '/tmp/shot3.png' });
await b.close();
